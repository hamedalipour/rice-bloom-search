// اصلاح متن دسته چای در products.ts (پس از تغییر کاتالوگ از پنل)
const fs = require('fs');
const p = 'src/data/products.ts';
let c = fs.readFileSync(p, 'utf8');
const reps = [
  ['خرید چای ایرانی اصل لاهیجان – سیاه، سبز و دمنوش', 'خرید چای ایرانی اصل لاهیجان – سیاه، بهاره و چوب'],
  ['چای سیاه، چای سبز و دمنوش با قیمت مناسب', 'چای سیاه، بهاره و چوب با قیمت مناسب'],
  ['چای سیاه بهاره لاهیجان، چای سبز باروتی گیلان و دمنوش گل محمدی کاشان، مستقیم', 'چای سیاه بهاره لاهیجان و چای چوب شمال (ساقه‌دار)، مستقیم'],
  ['چای سبز باروتی با طعم ملایم و خواص آنتی‌اکسیدانی، و دمنوش گل محمدی کاشان برای آرامش؛ سه انتخاب برای هر سلیقه‌ای.', 'چای چوب شمال با طعم اصیل و دم‌آوری طولانی؛ برای هر سلیقه و هر سفره‌ای.'],
  ['تفاوت چای سیاه و سبز چیست', 'تفاوت چای سیاه و چوب چیست'],
];
let n = 0;
for (const [a, b] of reps) {
  if (c.includes(a)) { c = c.split(a).join(b); n++; }
  else { console.log('NOT FOUND: ' + a.slice(0, 40)); }
}
fs.writeFileSync(p, c, 'utf8');
console.log('replacements applied: ' + n);
